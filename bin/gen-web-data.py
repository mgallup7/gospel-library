#!/usr/bin/env python3
"""Write web/lib/scriptures-data.js from the Python scripture metadata so the
browser and the sync job agree on books, chapters, citations and aliases."""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from gospel_library import scriptures  # noqa: E402

books, by_slug, aliases = scriptures._load()
data = {
    "books": [
        {
            "slug": b.slug, "name": b.name, "abbrev": b.abbrev, "uri": b.uri,
            "volume_slug": b.volume_slug, "volume_name": b.volume_name,
            "volume_index": b.volume_index, "book_index": b.book_index,
            "chapters": list(b.chapters), "group": b.group,
        }
        for b in books
    ],
    "aliases": {k: v.slug for k, v in aliases.items()},
}
out = ROOT / "web" / "lib" / "scriptures-data.js"
out.parent.mkdir(parents=True, exist_ok=True)
out.write_text("// Generated by bin/gen-web-data.py. Do not edit by hand.\nexport default "
               + json.dumps(data, ensure_ascii=False, separators=(",", ":")) + ";\n", encoding="utf-8")
print(f"{out}: {len(books)} books, {len(aliases)} aliases")
